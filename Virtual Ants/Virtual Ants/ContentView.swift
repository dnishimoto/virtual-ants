    private func foodColor(
        _ type: FoodType
    ) -> Color {

        switch type {

        case .seed:
            return .green

        case .fruit:
            return .red

        case .insect:
            return .purple

        case .nectar:
            return .yellow
        }
    }

    private func antColor(
        _ state: AntState
    ) -> Color {

        switch state {

        case .searching:
            return .white

        case .returning:
            return .orange

        case .resting:
            return .gray

        case .exploring:
            return .yellow
        }
    }
